#!/usr/bin/env python3
"""Create or refresh the FMI harness of one FIRE model.

usage: new_harness.py MODEL [--wrapper FILE.mo --wrapper-model NAME]
                            [--expect-refusal TEXT] [--stop S] [--step S] [--refresh]

Creates harnesses/MODEL/ with a Makefile (which includes ../../harness.mk),
builds out/model.fmu, and writes world.toml from the FMU's interface. A
starting harness.c and checks.toml are written only when absent; they are the
hand-maintained part of a harness. --refresh rewrites world.toml (for
example after the model's interface changed).
"""
import argparse, subprocess, sys, tomllib
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import fmu_vars  # noqa: E402

FMI_ROOT = Path(__file__).resolve().parent.parent
INT_TYPES = {"Int8", "UInt8", "Int16", "UInt16", "Int32", "UInt32", "Int64", "UInt64", "Enumeration"}
MAX_PRINTED = 8


def makefile(args) -> str:
    lines = ["# FMI harness for one FIRE model; the build rules are shared.", f"MODEL := {args.model}"]
    if args.wrapper:
        lines += [f"WRAPPER := {args.wrapper}", f"WRAPPER_MODEL := {args.wrapper_model}"]
    if args.expect_refusal:
        lines += [f"EXPECT_REFUSAL := {args.expect_refusal}"]
    return "\n".join(lines + ["include ../../harness.mk", ""])


def bindings(variables):
    """(inputs, outputs): lists of (alias, endpoint, variable, start) per scalar element."""
    taken, inputs, outputs = set(), [], []
    for v in variables:
        if v.causality not in ("input", "output") or v.type == "String":
            continue
        for element, start in v.elements():
            entry = (fmu_vars.alias(element, taken), f"m.{element}", v, start)
            (inputs if v.causality == "input" else outputs).append(entry)
    return inputs, outputs


def toml_value(value) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, list):
        return "[" + ", ".join(toml_value(v) for v in value) + "]"
    if isinstance(value, str):
        return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'
    return repr(value)


def world_toml(args, inputs, outputs, previous=None) -> str:
    """The world configuration; --refresh keeps the previous stop/step and the
    hand-written [Models.m.Parameters] overrides."""
    world = (previous or {}).get("World", {})
    stop, step = world.get("stop", round(args.stop * 1e9)), world.get("step", round(args.step * 1e9))
    parameters = (previous or {}).get("Models", {}).get("m", {}).get("Parameters", {})
    out = ["# Generated by tools/new_harness.py from out/model.fmu; refresh with --refresh",
           "# (keeps [World] stop/step and [Models.m.Parameters]).",
           "[World]", "start = 0", f"stop = {stop}", f"step = {step}",
           "time_unit = \"ns\"", "", "[Models.m]", "path = \"out/model.fmu\"", ""]
    if parameters:
        out += ["[Models.m.Parameters]"] + [f"{k} = {toml_value(v)}" for k, v in parameters.items()] + [""]
    out += ["[World.Inputs]"]
    out += [f"{a} = \"{e}\"" for a, e, _, _ in inputs]
    out += ["", "[World.Outputs]"] + [f"{a} = \"{e}\"" for a, e, _, _ in outputs]
    out += ["", "[Trace]", "every_step = true", "models = [\"m\"]", "output = \"out/trace.csv\"", "",
            "[Logging]", "output = \"out/runtime.log\"", "", "[Frontend]", "enabled = false", ""]
    return "\n".join(out)


def c_signal(variable, start: str) -> str:
    if variable.type == "Boolean":
        return "FH_CONSTANT(%d)" % (start.lower() == "true")
    try:
        return f"FH_CONSTANT({float(start or 0)!r})"
    except ValueError:
        return "FH_CONSTANT(0.0)"


def harness_c(args, inputs, outputs) -> str:
    def setter(v):
        return "FH_INPUT_BOOL" if v.type == "Boolean" else "FH_INPUT_INT" if v.type in INT_TYPES else "FH_INPUT"

    def getter(v):
        return "FH_OUTPUT_BOOL" if v.type == "Boolean" else "FH_OUTPUT_INT" if v.type in INT_TYPES else "FH_OUTPUT"

    lines = [f"/* FMI harness: {args.model}. Generated starting point; edit the scenario. */",
             '#include "fire_harness.h"', ""]
    if inputs:
        lines.append("static const fh_input_t inputs[] = {")
        lines += [f"    {setter(v)}({a}, {c_signal(v, s)})," for a, _, v, s in inputs]
        lines += ["};", ""]
    if outputs:
        lines.append("static const fh_output_t outputs[] = {")
        lines += [f"    {getter(v)}({a})," for a, _, v, _ in outputs[:MAX_PRINTED]]
        lines += ["};", ""]
    lines += ["int main(void) {", "  const fh_scenario_t scenario = {",
              f"      .title = \"{args.model}\",", f"      .stop_s = {args.stop!r},",
              "      .step_s = 0.01,", "      .print_s = 0.5,"]
    lines.append("      .inputs = inputs," if inputs else "      .inputs = NULL,")
    lines.append("      .input_count = FH_COUNT(inputs)," if inputs else "      .input_count = 0,")
    lines.append("      .outputs = outputs," if outputs else "      .outputs = NULL,")
    lines.append("      .output_count = FH_COUNT(outputs)," if outputs else "      .output_count = 0,")
    lines += ["  };", "  return fh_run(&scenario);", "}", ""]
    return "\n".join(lines)


CHECKS = """# Acceptance checks over out/trace.csv (see tools/check_trace.py).
# Columns are trace endpoints: m.<variable> or m.<variable>[k].
#
# [[check]]
# variable = "m.omega"   # one column, or a glob such as "m.rotor*"
# at = "end"             # "end" (default), "all", "max", "min", "mean", or a time in s
# range = [0.0, 1.0]     # or: near = 0.5 with tol = 1e-3
# why = "speed settles below omegaMax"

[[check]]
variable = "m.*"
at = "all"
finite = true
why = "every recorded value stays finite"
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("model")
    parser.add_argument("--wrapper")
    parser.add_argument("--wrapper-model")
    parser.add_argument("--expect-refusal")
    parser.add_argument("--stop", type=float, default=5.0)
    parser.add_argument("--step", type=float, default=0.001)
    parser.add_argument("--refresh", action="store_true")
    args = parser.parse_args()
    directory = FMI_ROOT / "harnesses" / args.model
    directory.mkdir(parents=True, exist_ok=True)
    if not (directory / "Makefile").exists():
        (directory / "Makefile").write_text(makefile(args))
    if args.expect_refusal:
        return 0
    subprocess.run(["make", "-s", "out/model.fmu"], cwd=directory, check=True)
    inputs, outputs = bindings(fmu_vars.read(directory / "out" / "model.fmu"))
    world = directory / "world.toml"
    if not world.exists() or args.refresh:
        previous = tomllib.loads(world.read_text()) if world.exists() else None
        world.write_text(world_toml(args, inputs, outputs, previous))
    if not (directory / "harness.c").exists():
        (directory / "harness.c").write_text(harness_c(args, inputs, outputs))
    if not (directory / "checks.toml").exists():
        (directory / "checks.toml").write_text(CHECKS)
    return 0


if __name__ == "__main__":
    sys.exit(main())
