"""The calibration report as Markdown (the JSON report holds everything)."""
from __future__ import annotations


def _f(x, nd=4):
    if x is None:
        return "unbounded"
    if isinstance(x, bool):
        return "yes" if x else "no"
    if isinstance(x, float):
        return f"{x:.{nd}g}"
    return str(x)


def _iv(iv):
    lo, hi = iv
    return f"[{_f(lo)}, {_f(hi)}]"


def markdown(r: dict) -> str:
    e = r["experiment"]
    L = []
    w = L.append
    w(f"# Calibration report: {e['name']}\n")
    w(f"{e['description']}. Created {r['created']}; experiment `{r['experiment_file']}` "
      f"(sha256 `{r['experiment_sha256'][:16]}…`).\n")
    if e.get("synthetic"):
        w("> **Synthetic.** Every dataset in this report was generated by the model itself, or by a richer "
          "model for the mismatch test. The results test the implementation and the experiment design. "
          "They are not a calibration or a validation of any real DPS310.\n")
    s = r["datasheet"]
    w("## Device and mode\n")
    w(f"- Part: {s['name']} (`{s['part']}`), level {s['level']} ({s['model']}), mode {s.get('mode') or 'low_noise'}")
    w(f"- Source: {s['source']}")
    w(f"- Unit: {e['unit']}\n")

    tc = r["toolchain"]
    v = tc["versions"]
    w("## Toolchain (milestone 1)\n")
    w(f"Rumoca `{v['rumoca']}` (sha256 `{v['rumoca_sha256'][:16]}…`), target {v['rumoca_target']}; FMPy {v['fmpy']}, "
      f"SciPy {v['scipy']}, NumPy {v['numpy']}, Python {v['python']}; library {v['library_revision'][:10]}"
      f"{' (uncommitted changes)' if v['library_dirty'] else ''}.\n")
    f = tc["fmu"]
    w(f"FMU `{f['file']}`: FMI {f['fmi_version']}, co-simulation {_f(f['co_simulation'])}, event mode "
      f"{_f(f['has_event_mode'])}. Fixed at compile time: {', '.join(f'`{x}`' for x in f['fixed_after_compile'])}.\n")
    w("| check | result | detail |\n|---|---|---|")
    for c in tc["checks"]:
        w(f"| {c['check']} | {'pass' if c['pass'] else '**FAIL**'} | {c['detail']} |")
    w("")

    w("## Datasheet-derived profile\n")
    w("| parameter | value | evidence | how |\n|---|---|---|---|")
    for k, p in s["parameters"].items():
        w(f"| `{k}` | {_f(p['value'])} | {p.get('class', '')} | {p['how']} |")
    w("")
    if s.get("unknown"):
        w("Unknown (no figure determines them):\n")
        for u in s["unknown"]:
            w(f"- {u}")
        w("")
    w("Datasheet figures not represented at this level:\n")
    for k, why in s["not_represented"].items():
        w(f"- `{k}`: {why}")
    w("")

    w("## Datasets\n")
    w("| dataset | role | rows | span (s) | readings sha256 | description |\n|---|---|---|---|---|---|")
    for n, d in r["datasets"].items():
        w(f"| {n} | {d['role']} | {d['rows']} | {d['span_s'][0]:.3f}–{d['span_s'][1]:.1f} | "
          f"`{d['sha256'][:12]}…` | {'synthetic' if d['synthetic'] else 'measured'}; {d['conditions']} |")
    w("")

    th = r["thresholds"]
    w(f"## Thresholds\n\nRead from `{th['file']}` (sha256 `{th['sha256'][:16]}…`) before any held-out evaluation: "
      f"{th['values']['holdout']}.\n")

    c = r["calibration"]
    lat = c["deterministic"]["latency"]
    w("## Calibration\n")
    w("**Stage 1, deterministic** (noise, drift and quantization off; least squares through the FMU).\n")
    w("| latencySamples | cost | rms (Pa) | Δ log-likelihood |\n|---|---|---|---|")
    for x in lat["candidates"]:
        w(f"| {x['latencySamples']} | {_f(x['cost'])} | {_f(x['rms'])} | {_f(x['delta_loglik'])} |")
    w(f"\nLatency: {lat['best']} samples; plausible {lat['plausible']} "
      f"({'identified' if lat['identifiable'] else 'not identified'}).\n")
    tb = c["deterministic"]["temperature"]
    w(f"Temperature offset: {_f(tb['estimate']['temperatureBias'])} K "
      f"(white-noise standard error {_f(tb['standard_error_white'].get('temperatureBias'))} K).\n")
    so = c["stochastic"]
    est = so["estimate"]
    w("**Stage 2, stochastic, jointly with the offset** (exact Gaussian likelihood of white noise plus a "
      "first-order Gauss-Markov drift; 95 % profile-likelihood intervals).\n")
    w("| parameter | estimate | interval95 | identifiable |\n|---|---|---|---|")
    for key, name in (("b", "pressureBias (Pa)"), ("sigma_w", "pressureNoiseStd (Pa)"),
                      ("sigma_d", "pressureDriftStd (Pa)"), ("tau", "pressureDriftTau (s)")):
        p = so["profiles"][key]
        w(f"| {name} | {_f(est[key])} | {_iv(p['interval95'])} | "
          f"{'yes' if p['identifiable'] else 'no'}{' (weakly)' if p.get('weakly_identified') else ''} |")
    dv = so["drift_vs_white_only"]
    w(f"\nDrift against white noise only: likelihood ratio {_f(dv['lr'])}, p = {_f(dv['p_value'])}. Innovations: "
      f"std {_f(so['innovation_std'])}, Ljung-Box p = {_f(so['innovations']['p_value'])}.\n")
    a = so["allan"]
    w("Allan deviation of the training residual: " + ", ".join(
        f"{_f(t, 3)} s: {_f(d, 3)} Pa" for t, d in list(zip(a["tau_s"], a["adev"]))[::4]) + ".\n")

    w("## Same-model recovery\n")
    w("Criterion: an identifiable parameter is recovered when |estimate − truth| ≤ 3 standard errors (z), the "
      "standard error taken from its 95 % interval; a 95 % interval misses the truth one time in twenty.\n")
    w("| parameter | truth | estimate | interval / plausible | identifiable | truth in interval | z | recovered |\n"
      "|---|---|---|---|---|---|---|---|")
    for x in r["recovery"]:
        iv = _iv(x["interval95"]) if "interval95" in x else str(x.get("plausible", ""))
        z = x.get("z")
        w(f"| `{x['parameter']}` | {_f(x['truth'])} | {_f(x['estimate'])} | {iv} | {_f(x['identifiable'])}"
          f"{' (weakly)' if x.get('weakly_identified') else ''} | {_f(x['truth_in_interval'])} | "
          f"{'' if z is None else f'{z:+.2f}'} | {_f(x.get('recovered'))} |")
    w("")

    w("## Identifiability\n")
    for name, x in r["identifiability"].items():
        w(f"- **{name}**: {x['question']}. Expected: {x['expected']}. "
          f"{'Flagged' if x['flagged'] else '**Not flagged**'}.")
        if "unidentifiable_directions" in x:
            w(f"  Relative singular values {[_f(v, 3) for v in x['relative_singular_values']]}; "
              f"unresolved direction {x['unidentifiable_directions']}.")
        else:
            w(f"  τ estimate {_f(x['tau_estimate'])} s, interval {_iv(x['tau_interval95'])}"
              f"{' (weakly identified)' if x['tau_weakly_identified'] else ''}; offset interval "
              f"{_iv(x['offset_interval95'])} Pa (truth {x['offset_truth']}).")
    w("")

    m = r["mismatch"]
    w("## Model mismatch\n")
    st = m["training_temperature_structure"]
    w(f"Generator: {m['generator']}; fitted: {m['fitted_model']}. Fitted offset {_f(m['pressureBias_fit'])} Pa.")
    if st.get("tested"):
        w(f"Training residual against temperature ({st['blocks']} blocks of 60 s): slope {_f(st['slope_pa_per_k'])} "
          f"± {_f(st['slope_se'])} Pa/K, p = {_f(st['p_value'])} → "
          f"{'**structured residual: behaviour the model does not represent**' if st['structured'] else 'no structure found'}.")
    h = m["holdout"]
    w(f"Held out at 45 °C: mean error {_f(h['mean_error_pa'])} Pa, innovation std {_f(h['innovation_std'])}, "
      f"Ljung-Box p {_f(h['ljung_box_p'])} → {'pass' if h['pass'] else '**fails the thresholds**'}. "
      f"Unexplained behaviour revealed: {_f(m['revealed'])}.\n")

    w("## Held-out comparison\n")
    w("| dataset | profile | mean error (Pa) | rms (Pa) | log-lik / reading | innovation std | Ljung-Box p | pass |\n"
      "|---|---|---|---|---|---|---|---|")
    for ev in r["holdout"]:
        for prof in ("calibrated", "datasheet_derived"):
            x = ev[prof]
            w(f"| {ev['dataset']} | {prof.replace('_', '-')} | {_f(x['mean_error_pa'])} | {_f(x['rms_error_pa'])} | "
              f"{_f(x['loglik_per_reading'])} | {_f(x['innovation_std'])} | {_f(x['ljung_box_p'])} | "
              f"{'pass' if x['pass'] else 'fail'} |")
    w("")
    for ev in r["holdout"]:
        t = ev["timing"]
        w(f"- {ev['dataset']} timing: {t['readings']} readings, spacing error ≤ {_f(t['max_spacing_error_s'], 3)} s, "
          f"first delivery {_f(t['first_delivery_s'])} s (expected {_f(t['expected_first_delivery_s'])} s).")
    w("")

    p = r["profile"]
    pc = r["profile_in_composer"]
    w("## Calibration profile\n")
    w(f"Written to `{p['path']}`. The composer accepts it: evidence **{pc['evidence']}**.\n")
    w("```toml\n" + p["text"].strip() + "\n```\n")

    w("## Limitations\n")
    for x in limitations(r):
        w(f"- {x}")
    w("")
    return "\n".join(L)


def limitations(r):
    out = []
    if r["experiment"].get("synthetic"):
        out.append("All data is synthetic. No property of a real DPS310 has been measured or validated here.")
    s = r["datasheet"]
    out += [f"Unknown from the datasheet: {u}." for u in s.get("unknown", [])]
    out += ["The reference is exact in synthetic data. A real reference's uncertainty enters the thresholds and fit "
            "weights.",
            "Quantization is treated as white noise of variance q²/12 in the likelihood.",
            "The drift model is first-order Gauss-Markov. A static record cannot show that slow variation is sensor "
            "drift rather than the environment or the reference.",
            "Latency is structural in the exported FMU (it sizes the delivery queue), so it is fitted over compiled "
            "variants, not continuously.",
            "B1 has no temperature-dependent offset, no supply sensitivity and no pressure clipping. The mismatch "
            "test shows how the temperature dependence appears when present."]
    return out
