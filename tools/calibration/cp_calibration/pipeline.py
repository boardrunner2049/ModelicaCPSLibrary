def toolchain_check(model: baro.Model) -> dict:
    out = {"versions": toolchain(), "checks": []}

    def check(name, ok, detail):
        out["checks"].append({"check": name, "pass": bool(ok), "detail": detail})

    s = model.slave({"latencySamples": 2})
    md = s.md
    out["fmu"] = {"file": s.path.name, "sha256": file_sha256(s.path), "fmi_version": md.fmiVersion,
                  "co_simulation": md.coSimulation is not None, "model_exchange": md.modelExchange is not None,
                  "has_event_mode": bool(md.coSimulation.hasEventMode),
                  "tunable_parameters": s.tunable(), "fixed_after_compile": s.fixed()}
    check("FMI 3 Co-Simulation export", md.fmiVersion.startswith("3") and md.coSimulation is not None,
          f"FMI {md.fmiVersion}, model identifier {md.coSimulation.modelIdentifier}")
    try:
        s._set("latencySamples", 3)
        check("structural parameters are refused at run time", False, "latencySamples was settable")
    except KeyError as e:
        check("structural parameters are refused at run time", True, str(e))

    # The plan's first concrete test.
    step = Trace(np.array([0.0, 1.05]), {"ambientPressure": np.array([100000.0, 100100.0]),
                                        "ambientTemperature": np.array([288.15, 288.15])})
    p = {"samplePeriod": 0.2, "pressureBias": 12.0}
    for h in (0.01, 0.05, 0.2):
        d = model.simulate(step, {**p, "latencySamples": 2}, 2.0, step=h)
        first = (float(d["pressure"][0]), float(d["deliveryTime"][0]), float(d["sampleTime"][0]))
        k = int(np.flatnonzero(d["pressure"] > 100100)[0])
        stepped = (float(d["pressure"][k]), float(d["deliveryTime"][k]), float(d["sampleTime"][k]))
        ok = (abs(first[0] - 100012) <= 1e-3 and abs(first[1] - 0.4) <= 1e-6 and abs(first[2] - 0.0) <= 1e-6
              and abs(stepped[0] - 100112) <= 1e-3 and abs(stepped[1] - 1.6) <= 1e-6
              and abs(stepped[2] - 1.2) <= 1e-6 and not d["missed"].any())
        check(f"step test, communication step {h} s", ok,
              f"first valid {first[0]:.6f} Pa delivered {first[1]:.9f} s (acquired {first[2]:.9f} s); "
              f"step {stepped[0]:.6f} Pa delivered {stepped[1]:.9f} s, acquired {stepped[2]:.9f} s")
    # Bias recovered from that synthetic trace through the harness.
    ds = _write_step_dataset(model, step, p)
    f = baro.fit_deterministic(model, [ds], {**p, "latencySamples": 2}, ["pressureBias"],
                               {"pressureBias": 0.0}, {"pressureBias": (-200, 200)})
    check("step test: offset recovered by the fit", abs(f["estimate"]["pressureBias"] - 12) <= 1e-6,
          f"pressureBias = {f['estimate']['pressureBias']:.9f} Pa (truth 12), rms {f['rms']:.2e} Pa")

    # Every tunable parameter changes behaviour when excited.
    excite = Trace(np.array([0.0, 2.0]), {"ambientPressure": np.array([1e5, 100050.0]),
                                         "ambientTemperature": np.array([288.15, 300.0])})
    base = {"samplePeriod": 0.05, "pressureNoiseStd": 0.5, "pressureDriftStd": 3.0, "pressureDriftTau": 10.0,
            "temperatureNoiseStd": 0.1, "seed": 1, "streamId": 301, "latencySamples": 2}
    ref = model.simulate(excite, base, 10.0, step=0.01)
    inert = []
    for k, v in [("seed", 2), ("streamId", 302), ("pressureDriftTau", 1.0), ("samplePeriod", 0.04),
                 ("pressureNoiseStd", 1.0), ("pressureDriftStd", 1.0), ("pressureQuantum", 1.0),
                 ("temperatureNoiseStd", 0.5), ("temperatureQuantum", 0.5), ("pressureBias", 1.0),
                 ("temperatureBias", 1.0), ("altitudeBias", 1.0), ("startTime", 0.01)]:
        d = model.simulate(excite, {**base, k: v}, 10.0, step=0.01)
        n = min(len(d["pressure"]), len(ref["pressure"]))
        same = all(np.array_equal(d[c][:n], ref[c][:n]) for c in ("pressure", "temperature", "altitude", "sampleTime"))
        if same:
            inert.append(k)
    check("every tunable parameter changes the output", not inert,
          "inert: " + ", ".join(inert) if inert else "13 parameters perturbed, each changes the delivered readings")

    # Reset, seed and communication-step reproducibility.
    noisy = {**base, "pressureQuantum": 0.06}
    a = model.simulate(excite, noisy, 10.0, step=0.01)
    b = model.simulate(excite, noisy, 10.0, step=0.01)
    c = model.simulate(excite, noisy, 10.0, step=0.025)
    check("reset: repeated runs of one instance agree exactly", np.array_equal(a["pressure"], b["pressure"]),
          f"{len(a['pressure'])} readings")
    check("communication step does not change the readings (step <= period)",
          np.array_equal(a["pressure"], c["pressure"]) and np.array_equal(a["sampleTime"], c["sampleTime"]),
          "0.01 s and 0.025 s steps")
    fresh = baro.Model()
    e = fresh.simulate(excite, noisy, 10.0, step=0.01)
    fresh.close()
    check("a fresh instance reproduces a reused one", np.array_equal(a["pressure"], e["pressure"]), "same seed")
    off = {**base, "pressureNoiseStd": 0, "pressureDriftStd": 0, "temperatureNoiseStd": 0}
    x = model.simulate(excite, off, 10.0, step=0.01)
    y = model.simulate(excite, off, 10.0, step=0.025)
    check("noise off: runs agree within 1e-9 Pa", np.max(np.abs(x["pressure"] - y["pressure"])) <= 1e-9,
          f"max difference {np.max(np.abs(x['pressure'] - y['pressure'])):.1e} Pa")
    coarse = model.simulate(excite, noisy, 10.0, step=0.12)
    missed = int(coarse["missed"].sum())
    check("a step coarser than the period is detected through the sequence", missed > 0,
          f"step 0.12 s, period 0.05 s: {missed} readings counted as missed by sequence jumps")
    out["pass"] = all(c["pass"] for c in out["checks"])
    return out


def _write_step_dataset(model, trace, p):
    d = model.simulate(trace, {**p, "latencySamples": 2}, 2.0, step=0.01)
    path = LIBRARY_ROOT / "build/calibration/toolchain/step_test"
    return dsmod.write(path, {"time_s": d["deliveryTime"], "pressure_pa": d["pressure"],
                              "temperature_k": d["temperature"]},
                       {"time_s": trace.time, "pressure_pa": trace.values["ambientPressure"],
                        "temperature_k": trace.values["ambientTemperature"]},
                       {"synthetic": True, "description": "the plan's step test, generated by B1"})


# --- synthetic data ---------------------------------------------------------------

def stimulus(spec: dict) -> Trace:
    dur = float(spec["duration_s"])
    p0 = float(spec.get("pressure_pa", 100000.0))
    t0 = float(spec.get("temperature_c", 25.0)) + 273.15
    kind = spec["stimulus"]
    if kind == "static":
        return Trace(np.array([0.0]), {"ambientPressure": np.array([p0]), "ambientTemperature": np.array([t0])})
    if kind == "steps":
        every = float(spec.get("step_every_s", 10.05))
        size = float(spec.get("step_pa", 100.0))
        t = np.arange(0.0, dur, every)
        p = p0 + size * (np.arange(len(t)) % 2)
        return Trace(t, {"ambientPressure": p, "ambientTemperature": np.full(len(t), t0)})
    if kind == "temperature_ramp":
        t = np.arange(0.0, dur, 1.0)
        t1 = float(spec["temperature_end_c"]) + 273.15
        return Trace(t, {"ambientPressure": np.full(len(t), p0), "ambientTemperature": t0 + (t1 - t0) * t / dur})
    raise ValueError(f"stimulus {kind!r}")


def generate(model: baro.Model, truth: dict, spec: dict, out_dir: Path, meta: dict) -> dsmod.Dataset:
    trace = stimulus(spec)
    params = {**truth, "seed": int(spec["seed"]), **spec.get("parameters", {})}
    d = model.simulate(trace, params, float(spec["duration_s"]))
    readings = {"time_s": d["deliveryTime"], "pressure_pa": d["pressure"], "temperature_k": d["temperature"],
                "altitude_m": d["altitude"]}
    reference = {"time_s": trace.time, "pressure_pa": trace.values["ambientPressure"],
                 "temperature_k": trace.values["ambientTemperature"]}
    return dsmod.write(out_dir / spec["name"], readings, reference, {
        **meta, "synthetic": True, "stimulus": spec, "truth": params,
        "time_base": "simulation time; time_s is each reading's delivery time",
        "reference": {"kind": "the generating input trace (exact)", "uncertainty_pa": 0.0, "clock_offset_s": 0.0},
        "conditions": {"temperature_c": spec.get("temperature_c", 25.0), "pressure_pa": spec.get("pressure_pa", 1e5)}})


# --- calibration ------------------------------------------------------------------

def stochastic_stage(model, datasets, params, T, quantum, bounds) -> dict:
    """Residuals of the deterministic prediction (offset excluded), then the
    offset, white noise and drift jointly by maximum likelihood, with profile
    intervals for each."""
    p = {**params, **baro.STOCHASTIC_OFF, "pressureBias": 0.0}
    e = np.concatenate([baro.residuals(model, ds, p) for ds in datasets])
    e = -e[np.isfinite(e)]                    # observed - predicted
    est = st.fit(e, T, bounds, quantum)
    grids = {"b": np.linspace(est["b"] - 8 * est["sigma_d"] - 1, est["b"] + 8 * est["sigma_d"] + 1, 25),
             "sigma_w": np.geomspace(max(est["sigma_w"] / 3, bounds.sigma_w[0]), min(est["sigma_w"] * 3, bounds.sigma_w[1]), 19),
             "sigma_d": np.geomspace(bounds.sigma_d[0] * 10, bounds.sigma_d[1] / 10, 25),
             "tau": np.geomspace(bounds.tau[0] * 2, bounds.tau[1] / 2, 25)}
    prof = {n: st.profile(e, T, bounds, n, g, quantum, mle=est) for n, g in grids.items()}
    ll, nu = st.loglik(e, T, est["b"], est["sigma_w"], est["sigma_d"], est["tau"], quantum, innovations=True)
    white = st.fit(e, T, bounds, quantum, drift=False)
    lr = 2 * (est["loglik"] - white["loglik"])
    return {"estimate": est, "profiles": prof, "n": len(e), "innovations": st.ljung_box(nu),
            "innovation_std": float(np.std(nu)), "allan": st.allan_deviation(e - est["b"], T),
            "drift_vs_white_only": {"lr": float(lr), "p_value": float(stats.chi2.sf(lr, 2)),
                                     "white_only_sigma": white["sigma_w"]},
            "residual_mean": float(np.mean(e)), "residual_std": float(np.std(e))}


def temperature_structure(model, ds, params, block_s: float = 60.0) -> dict:
    """Does the residual depend on temperature? Block means (roughly
    independent for blocks longer than the drift time) regressed on the block
    temperature."""
    p = {**params, **baro.STOCHASTIC_OFF}
    e = -baro.residuals(model, ds, p)
    t = ds.readings["time_s"]
    T_ref = baro.held({"deliveryTime": ds.reference["time_s"], "x": ds.reference["temperature_k"]}, t, "x")
    ok = np.isfinite(e) & np.isfinite(T_ref)
    blocks = np.floor(t[ok] / block_s)
    keys = np.unique(blocks)
    em = np.array([e[ok][blocks == k].mean() for k in keys])
    tm = np.array([T_ref[ok][blocks == k].mean() for k in keys])
    if np.ptp(tm) < 1e-9 or len(keys) < 4:
        return {"tested": False, "reason": "temperature constant in this dataset"}
    r = stats.linregress(tm, em)
    return {"tested": True, "blocks": int(len(keys)), "slope_pa_per_k": float(r.slope),
            "slope_se": float(r.stderr), "p_value": float(r.pvalue), "r": float(r.rvalue),
            "structured": bool(r.pvalue < 0.01)}


def evaluate(model, ds, profile_params, T, quantum, thresholds) -> dict:
    """A profile's prediction of a held-out dataset: offset, the likelihood of
    the residuals under its own stochastic model, innovation whiteness."""
    p = {**profile_params, **baro.STOCHASTIC_OFF}
    e = -baro.residuals(model, ds, p)
    e = e[np.isfinite(e)]
    sw, sd, tau = (float(profile_params.get("pressureNoiseStd", 0)), float(profile_params.get("pressureDriftStd", 0)),
                   float(profile_params.get("pressureDriftTau", 300)))
    q = float(profile_params.get("pressureQuantum", quantum))
    ll, nu = st.loglik(e, T, 0.0, sw, sd, tau, q, innovations=True)
    lb = st.ljung_box(nu)
    res = {"n": int(len(e)), "mean_error_pa": float(np.mean(e)), "rms_error_pa": float(np.sqrt(np.mean(e ** 2))),
           "loglik_per_reading": float(ll / len(e)), "innovation_std": float(np.std(nu)),
           "ljung_box_p": lb["p_value"]}
    th = thresholds
    res["checks"] = {
        "mean_error": abs(res["mean_error_pa"]) <= th["mean_error_pa"],
        "innovation_std": th["innovation_std"][0] <= res["innovation_std"] <= th["innovation_std"][1],
        "innovations_white": res["ljung_box_p"] >= th["ljung_box_p_min"]}
    res["pass"] = all(res["checks"].values())
    return res


def timing_check(ds, T, L) -> dict:
    meta = ds.meta.get("truth", {})
    d = ds.readings
    spacing = np.diff(d["time_s"])
    return {"readings": int(len(spacing) + 1), "period_s": T, "latency_samples": L,
            "max_spacing_error_s": float(np.max(np.abs(spacing - T))) if len(spacing) else 0.0,
            "first_delivery_s": float(d["time_s"][0]),
            "expected_first_delivery_s": float(meta.get("startTime", 0.0) + L * T)}


def run(experiment: Path, out: Path | None = None) -> dict:
    exp = tomllib.loads(Path(experiment).read_text())
    e = exp["experiment"]
    out = Path(out or LIBRARY_ROOT / "build/calibration" / e["name"])
    out.mkdir(parents=True, exist_ok=True)
    report = {"experiment": e, "experiment_file": rel(experiment),
              "experiment_sha256": file_sha256(Path(experiment)),
              "created": _dt.datetime.now(_dt.timezone.utc).isoformat(timespec="seconds")}
    model = baro.Model()
    try:
        report["toolchain"] = toolchain_check(model)

        sheet = baro.datasheet_report(e["part"], e.get("mode"))
        report["datasheet"] = sheet
        ds_params = baro.parameters_of(sheet)
        T = float(ds_params["samplePeriod"])
        quantum = float(ds_params.get("pressureQuantum", 0.0))

        truth = {**ds_params, **exp.get("truth", {})}
        meta = {"description": e["description"], "unit": e["unit"], "part": e["part"], "mode": e.get("mode", "")}
        data = {}
        for spec in exp["datasets"]:
            data[spec["name"]] = dsmod.obtain(spec, Path(experiment).parent,
                                              lambda spec=spec: generate(model, truth, spec, out / "data", meta),
                                              "barometer")
        report["datasets"] = {n: {**d.summary(), "role": s["role"]}
                              for (n, d), s in zip(data.items(), exp["datasets"])}
        train = [data[s["name"]] for s in exp["datasets"] if s["role"] == "train"]
        steps = [data[s["name"]] for s in exp["datasets"] if s["role"] == "train" and s["stimulus"] == "steps"]
        static = [data[s["name"]] for s in exp["datasets"] if s["role"] == "train" and s["stimulus"] == "static"]
        holdout = [(s, data[s["name"]]) for s in exp["datasets"] if s["role"] == "holdout"]

        # Thresholds are fixed before the held-out data is evaluated.
        th_path = Path(experiment).parent / e["thresholds"]
        thresholds = tomllib.loads(th_path.read_text())
        report["thresholds"] = {"file": rel(th_path), "sha256": file_sha256(th_path),
                                "values": thresholds, "read_before_holdout_evaluation": True}

        fit = exp["fit"]
        base = {k: v for k, v in ds_params.items() if k not in ("seed", "streamId")}
        lat = baro.fit_latency(model, steps, base, fit["latency_candidates"], ["pressureBias"],
                               {"pressureBias": 0.0}, {"pressureBias": tuple(fit["pressure_bias_bounds_pa"])})
        L = lat["best"]
        tb = baro.fit_deterministic(model, train, {**base, "latencySamples": L}, ["temperatureBias"],
                                    {"temperatureBias": 0.0}, {"temperatureBias": (-5, 5)}, channels=["temperature"])
        det = {"latency": lat, "temperature": tb}
        b = fit["stochastic_bounds"]
        bounds = st.Bounds(tuple(b["sigma_w"]), tuple(b["sigma_d"]), tuple(b["tau"]))
        sto = stochastic_stage(model, static, {**base, "latencySamples": L}, T, quantum, bounds)
        report["calibration"] = {"deterministic": det, "stochastic": sto}

        est = sto["estimate"]
        calibrated = {**base, "latencySamples": L, "pressureBias": est["b"], "pressureNoiseStd": est["sigma_w"],
                      "temperatureBias": tb["estimate"]["temperatureBias"]}
        prof = sto["profiles"]
        drift_ok = prof["sigma_d"]["identifiable"] and prof["tau"]["identifiable"]
        if drift_ok:
            calibrated.update(pressureDriftStd=est["sigma_d"], pressureDriftTau=est["tau"])

        # Recovery (synthetic only): truth inside each identifiable interval.
        # Recorded data states no truth; the design checks below then simulate
        # with the calibrated values.
        if "truth" not in exp:
            truth = {**truth, **calibrated}
        tr = exp.get("truth")
        rec = []
        if tr is not None:
            pairs = [("pressureBias", "b"), ("pressureNoiseStd", "sigma_w"), ("pressureDriftStd", "sigma_d"),
                     ("pressureDriftTau", "tau")]
            for name, key in pairs:
                pr = prof[key]
                lo, hi = pr["interval95"]
                inside = (lo is None or lo <= tr[name]) and (hi is None or tr[name] <= hi)
                # Recovery criterion: within 3 standard errors, the standard error
                # taken from the 95 % interval (in log space for scale parameters).
                z = None
                if lo is not None and hi is not None:
                    if key == "b":
                        z = (est[key] - tr[name]) / ((hi - lo) / (2 * 1.959964))
                    else:
                        z = math.log(est[key] / tr[name]) / (math.log(hi / lo) / (2 * 1.959964))
                rec.append({"parameter": name, "truth": tr[name], "estimate": est[key], "interval95": [lo, hi],
                            "identifiable": pr["identifiable"], "weakly_identified": pr.get("weakly_identified", False),
                            "truth_in_interval": bool(inside), "z": z,
                            "recovered": bool(z is not None and abs(z) <= 3) if pr["identifiable"] else None})
            rec.append({"parameter": "latencySamples", "truth": tr["latencySamples"], "estimate": L,
                        "plausible": lat["plausible"], "identifiable": lat["identifiable"],
                        "truth_in_interval": tr["latencySamples"] in lat["plausible"],
                        "recovered": L == tr["latencySamples"]})
            rec.append({"parameter": "temperatureBias", "truth": tr["temperatureBias"],
                        "estimate": tb["estimate"]["temperatureBias"],
                        "identifiable": not tb["unidentifiable_directions"],
                        "truth_in_interval": abs(tb["estimate"]["temperatureBias"] - tr["temperatureBias"])
                        <= max(4 * tb["standard_error_white"].get("temperatureBias", 0), 0.005 + 1e-9),
                        "recovered": abs(tb["estimate"]["temperatureBias"] - tr["temperatureBias"])
                        <= max(3 * tb["standard_error_white"].get("temperatureBias", 0), 0.01 / math.sqrt(12))})
        report["recovery"] = rec

        report["identifiability"] = identifiability_cases(model, exp, truth, out, base, bounds, T, quantum, meta)
        report["mismatch"] = (mismatch_case(exp, truth, out, base, T, quantum, thresholds, meta)
                              if "mismatch" in exp else None)

        evals = []
        for spec, d in holdout:
            evals.append({"dataset": spec["name"],
                          "calibrated": evaluate(model, d, calibrated, T, quantum, thresholds["holdout"]),
                          "datasheet_derived": evaluate(model, d, {**base, "latencySamples": 0}, T, quantum,
                                                        thresholds["holdout"]),
                          "timing": timing_check(d, T, (tr or {}).get("latencySamples", L))})
        report["holdout"] = evals

        report["profile"] = write_profile(out / f"{e['name']}.profile.toml", exp, report, calibrated, prof, lat, tb)
        report["profile_in_composer"] = baro.datasheet_report(e["part"], e.get("mode"),
                                                              calibration=str(out / f"{e['name']}.profile.toml"))
    finally:
        model.close()
    (out / "report.json").write_text(json.dumps(report, indent=1, default=_json) + "\n")
    from .report import markdown
    (out / "report.md").write_text(markdown(report))
    return report


def _json(o):
    if isinstance(o, (np.floating, np.integer)):
        return o.item()
    if isinstance(o, np.ndarray):
        return o.tolist()
    if isinstance(o, np.bool_):
        return bool(o)
    return str(o)


def identifiability_cases(model, exp, truth, out, base, bounds, T, quantum, meta) -> dict:
    cases = {}
    idf = exp.get("identifiability", {})
    # (1) Structural: offset and altitude offset from an altitude-only log.
    spec = {"name": "altitude_only", "stimulus": "steps", "duration_s": 60, "seed": 41,
            "parameters": {"pressureNoiseStd": 0, "pressureDriftStd": 0, "pressureQuantum": 0, "altitudeBias": 2.0}}
    d = generate(model, truth, spec, out / "data", meta)
    f = baro.fit_deterministic(model, [d], {**base, "latencySamples": truth["latencySamples"]},
                               ["pressureBias", "altitudeBias"], {"pressureBias": 0.0, "altitudeBias": 0.0},
                               {"pressureBias": (-200, 200), "altitudeBias": (-50, 50)}, channels=["altitude"])
    cases["altitude_only_offsets"] = {
        "question": "can pressureBias and altitudeBias be told apart from the altitude output alone?",
        "expected": "no: altitude = altitude_w + altitudeBias - k*pressureBias, one combination",
        "relative_singular_values": f["relative_singular_values"],
        "unidentifiable_directions": f["unidentifiable_directions"],
        "flagged": bool(f["unidentifiable_directions"])}
    # (2) Practical: drift time constant from a record shorter than it.
    short = idf.get("short_record", {"duration_s": 30, "tau_s": 300, "seed": 42})
    spec = {"name": "short_static", "stimulus": "static", "duration_s": short["duration_s"], "seed": short["seed"],
            "parameters": {"pressureDriftTau": short["tau_s"]}}
    d = generate(model, truth, spec, out / "data", meta)
    p = {**base, **baro.STOCHASTIC_OFF, "latencySamples": truth["latencySamples"], "pressureBias": 0.0}
    e = baro.residuals(model, d, p)
    e = -e[np.isfinite(e)]
    est = st.fit(e, T, bounds, quantum)
    pr = st.profile(e, T, bounds, "tau", np.geomspace(bounds.tau[0] * 2, bounds.tau[1] / 2, 25), quantum, mle=est)
    pb = st.profile(e, T, bounds, "b", np.linspace(est["b"] - 60, est["b"] + 60, 25), quantum, mle=est)
    cases["short_record_drift"] = {
        "question": f"drift correlation time ({short['tau_s']} s) from a {short['duration_s']} s static record",
        "expected": "not bounded, or only weakly: the record is shorter than the correlation time",
        "tau_estimate": est["tau"], "tau_interval95": pr["interval95"], "tau_identifiable": pr["identifiable"],
        "tau_weakly_identified": pr["weakly_identified"],
        "offset_interval95": pb["interval95"], "offset_truth": truth["pressureBias"],
        "flagged": (not pr["identifiable"]) or pr["weakly_identified"]}
    return cases


def mismatch_case(exp, truth, out, base, T, quantum, thresholds, meta) -> dict:
    """Data from a richer model (B1 plus a temperature-dependent offset), fitted
    with B1. Parameters of the richer model are not expected back; the report
    must show the unexplained behaviour."""
    m = exp["mismatch"]
    rich = baro.Model(wrapper=MISMATCH_MODEL, wrapper_model="BarometerTemperatureOffset")
    simple = baro.Model()
    try:
        rich_truth = {**truth, "temperatureCoefficient": m["temperature_coefficient_pa_per_k"]}
        rich_truth = {k: v for k, v in rich_truth.items() if k in rich.slave({"latencySamples": truth["latencySamples"]}).vars
                      or k == "latencySamples"}
        tr = generate(rich, rich_truth, m["train"], out / "data", {**meta, "generator": "BarometerTemperatureOffset"})
        ho = generate(rich, rich_truth, m["holdout"], out / "data", {**meta, "generator": "BarometerTemperatureOffset"})
        L = truth["latencySamples"]
        f = baro.fit_deterministic(simple, [tr], {**base, "latencySamples": L}, ["pressureBias"],
                                   {"pressureBias": 0.0}, {"pressureBias": (-200, 200)})
        fitted = {**base, "latencySamples": L, "pressureBias": f["estimate"]["pressureBias"],
                  "pressureNoiseStd": truth["pressureNoiseStd"], "pressureDriftStd": truth["pressureDriftStd"],
                  "pressureDriftTau": truth["pressureDriftTau"]}
        structure = temperature_structure(simple, tr, fitted)
        held = evaluate(simple, ho, fitted, T, quantum, thresholds["holdout"])
        return {"generator": "BarometerTemperatureOffset (B1 + 0.5 Pa/K about 25 °C)",
                "fitted_model": "B1 (no temperature dependence)", "pressureBias_fit": f["estimate"]["pressureBias"],
                "training_temperature_structure": structure, "holdout": held,
                "revealed": bool(structure.get("structured")) or not held["pass"]}
    finally:
        rich.close()
        simple.close()


def write_profile(path: Path, exp, report, calibrated, prof, lat, tb) -> dict:
    e = exp["experiment"]
    names = {d: report["datasets"][d] for d in report["datasets"] if report["datasets"][d]["role"] == "train"}
    train_static = "+".join(n for n in names if exp_spec(exp, n)["stimulus"] == "static")
    train_steps = "+".join(n for n in names if exp_spec(exp, n)["stimulus"] == "steps")
    lines = ["# Calibration profile written by tools/calibration (cp_calibration).",
             "# Overlay it on the part: [models.barometer] part = ..., calibration = \"<this file>\".", "",
             "[profile]", f'kind = "barometer"', f'part = "{e["part"]}"', 'level = "B1"',
             f'mode = "{e.get("mode", "low_noise")}"', f'unit = "{e["unit"]}"',
             f'label = "{e["label"]}"', f'synthetic = {str(bool(e.get("synthetic"))).lower()}',
             f'created = "{report["created"]}"', f'experiment = "{report["experiment_file"]}"',
             f'experiment_sha256 = "{report["experiment_sha256"]}"',
             f'library_revision = "{report["toolchain"]["versions"]["library_revision"]}"',
             f'rumoca = "{report["toolchain"]["versions"]["rumoca"]}"',
             f'fmpy = "{report["toolchain"]["versions"]["fmpy"]}"', ""]
    for n, d in report["datasets"].items():
        lines += [f"[datasets.{n}]", f'role = "{d["role"]}"', f'readings_sha256 = "{d["sha256"]}"',
                  f'reference_sha256 = "{d["reference_sha256"]}"', f"synthetic = {str(d['synthetic']).lower()}", ""]

    def interval(p):
        lo, hi = p["interval95"]
        return f"[{float(lo) if lo is not None else 'nan'}, {float(hi) if hi is not None else 'nan'}]"

    entries = [("pressureBias", calibrated["pressureBias"], train_static,
                "joint maximum likelihood with the noise and drift model (Kalman filter)", prof["b"]),
               ("pressureNoiseStd", calibrated["pressureNoiseStd"], train_static,
                "maximum likelihood, white noise beside the drift; quantization as q^2/12", prof["sigma_w"])]
    if "pressureDriftStd" in calibrated:
        entries += [("pressureDriftStd", calibrated["pressureDriftStd"], train_static,
                     "maximum likelihood, first-order Gauss-Markov drift", prof["sigma_d"]),
                    ("pressureDriftTau", calibrated["pressureDriftTau"], train_static,
                     "maximum likelihood, first-order Gauss-Markov drift", prof["tau"])]
    lines.append("[parameters]")
    for name, value, dsn, how, p in entries:
        lines += [f"{name} = {{ value = {float(value)!r}, class = \"measured\", dataset = \"{dsn}\", "
                  f"how = \"{how}\", interval95 = {interval(p)}, interval_method = \"profile likelihood\" }}"]
    lines += [f"latencySamples = {{ value = {int(calibrated['latencySamples'])}, class = \"measured\", "
              f"dataset = \"{train_steps}\", how = \"least squares at each candidate latency (structural: compiled per variant)\", "
              f"plausible = {[int(x) for x in lat['plausible']]} }}"]
    se = float(tb["standard_error_white"].get("temperatureBias", float("nan")))
    lines += [f"temperatureBias = {{ value = {float(calibrated['temperatureBias'])!r}, class = \"measured\", "
              f"dataset = \"{'+'.join(names)}\", how = \"least squares on the temperature channel\", "
              f"standard_error = {se!r} }}", ""]
    not_id = [k for k, key in (("pressureDriftStd", "sigma_d"), ("pressureDriftTau", "tau")) if not prof[key]["identifiable"]]
    if not_id:
        lines += ["[not_identified]"] + [f'{k} = "the training data does not bound it; the datasheet-derived value stays"'
                                         for k in not_id] + [""]
    path.write_text("\n".join(lines))
    return {"path": str(path), "sha256": file_sha256(path), "text": path.read_text()}


def exp_spec(exp, name):
    return next(s for s in exp["datasets"] if s["name"] == name)
