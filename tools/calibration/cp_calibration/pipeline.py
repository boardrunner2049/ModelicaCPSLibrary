"""The barometer calibration pipeline, from a part file to a report.

    toolchain   milestone 1: the exported FMU loads, every tunable parameter
                changes the output, reset/seed/step reproducibility, and the
                plan's step test
    datasheet   the composer's datasheet-derived profile with evidence classes
    synthetic   datasets generated by the model itself (recovery) and by a
                richer model (mismatch); never presented as a device
    calibrate   staged fit: deterministic offset and latency, then the
                stochastic model jointly with the offset; identifiability
    evaluate    held-out comparison of the calibrated and datasheet-derived
                profiles against thresholds read (and hashed) before the
                held-out data is touched
"""
