"""Write a C shim that links a prepared vehicle FMU into the host program.

`prepare MODEL.fmu OUT_DIR --shim NAME` writes OUT_DIR/shim/ next to the
descriptor:

  cpv_model_NAME.c   `const cpv_model_t cpv_model_NAME`: the descriptor's
                     content as C data, and the model's FMI 3 functions
  sources/           the FMU's C sources, as shipped in the FMU
  cpv_model.cmake    name, sources and preprocessor definitions for the
                     runtime build (cmake -DCPV_MODELS=OUT_DIR/shim)

Both artifacts come from the same checked FMU: the shim holds exactly the
value references, shapes, start values, capabilities and parameters of the
descriptor. The model is compiled from source with FMI 3's source-code
function prefix (modelIdentifier_), so the host needs no shared library and
no descriptor file at run time.
"""
from __future__ import annotations

import math
from pathlib import Path
import re
import shutil
import xml.etree.ElementTree as ET

SHIM_DIR = "shim"
NAME_PATTERN = re.compile(r"[a-z][a-z0-9_]{0,47}")
# The definition Rumoca uses to export unprefixed names from the shared library.
SHARED_LIBRARY_ONLY = {"FMI3_OVERRIDE_FUNCTION_PREFIX"}
FMI3_FUNCTIONS = (
    ("instantiate_co_simulation", "fmi3InstantiateCoSimulation"),
    ("free_instance", "fmi3FreeInstance"),
    ("enter_initialization_mode", "fmi3EnterInitializationMode"),
    ("exit_initialization_mode", "fmi3ExitInitializationMode"),
    ("do_step", "fmi3DoStep"),
    ("get_float64", "fmi3GetFloat64"),
    ("set_float64", "fmi3SetFloat64"),
    ("get_int32", "fmi3GetInt32"),
    ("reset", "fmi3Reset"),
    ("terminate", "fmi3Terminate"),
)


def c_string(text: str | None) -> str:
    if text is None:
        return "NULL"
    out = []
    for ch in text:
        if ch in '"\\':
            out.append("\\" + ch)
        elif " " <= ch <= "~":
            out.append(ch)
        else:
            out.extend(f"\\{b:03o}" for b in ch.encode())
    return '"' + "".join(out) + '"'


def c_double(value: float) -> str:
    value = float(value)
    if not math.isfinite(value):
        raise ValueError(f"{value} cannot be written as a C double constant")
    return repr(value)  # shortest round-trip form; always has '.' or 'e'


def read_build_description(sources: Path, identifier: str) -> tuple[list[str], list[str]]:
    """Source files and preprocessor definitions for the model's build configuration."""
    path = sources / "buildDescription.xml"
    if not path.is_file():
        raise ValueError(f"{sources} has no buildDescription.xml")
    root = ET.parse(path).getroot()
    configs = [c for c in root.iter("BuildConfiguration")
               if c.get("modelIdentifier") == identifier]
    if len(configs) != 1:
        raise ValueError(f"buildDescription.xml has no single BuildConfiguration for {identifier}")
    files, definitions = [], []
    for fileset in configs[0].iter("SourceFileSet"):
        if fileset.get("language", "C99") not in ("C89", "C90", "C99", "C11"):
            raise ValueError(f"source file set in {fileset.get('language')} is not supported")
        if any(True for _ in fileset.iter("IncludeDirectory")) or fileset.get("compilerOptions"):
            raise ValueError("include directories and compiler options are not supported")
        for f in fileset.iter("SourceFile"):
            name = f.get("name", "")
            if not name or Path(name).is_absolute() or ".." in Path(name).parts:
                raise ValueError(f"source file {name!r} is not a relative path inside sources/")
            if not (sources / name).is_file():
                raise ValueError(f"source file {name} is listed but missing")
            files.append(name)
        for d in fileset.iter("PreprocessorDefinition"):
            name = d.get("name", "")
            if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name):
                raise ValueError(f"preprocessor definition {name!r} is malformed")
            if name in SHARED_LIBRARY_ONLY or name == "FMI3_FUNCTION_PREFIX":
                continue
            value = d.get("value")
            if value is not None and not re.fullmatch(r"[A-Za-z0-9_.+-]*", value):
                raise ValueError(f"preprocessor definition {name}={value!r} is not supported")
            definitions.append(name if value is None else f"{name}={value}")
    if not files:
        raise ValueError("buildDescription.xml lists no source files")
    return files, definitions


def render(descriptor: dict, name: str, resources_uri: str | None) -> str:
    art = descriptor["artifact"]
    lines = [
        f"/* Generated by cp_vehicle_interface prepare --shim {name}. Do not edit; prepare again.",
        f" * Model {art['model_name']} ({art['generation_tool']}), FMI {art['fmi_version']}",
        f" * FMU {art['source']}",
        f" * FMU sha256 {art['source_sha256']}",
        f" * Contract {descriptor['contract']['name']} version {descriptor['contract']['version']},"
        f" profile {descriptor['profile']}. */",
        '#include "cpvehicle/cpvehicle_model.h"',
        "",
        "/* FMI 3 source-code naming: every function carries the model identifier. */",
        f"#define FMI3_FUNCTION_PREFIX {art['model_identifier']}_",
        '#include "fmi3Functions.h"',
        "",
    ]
    fields = []
    for cap, entries in descriptor["capabilities"].items():
        for field, entry in entries.items():
            if entry is None:
                continue
            start = "NULL"
            if entry.get("start") is not None:
                start = f"start_{len(fields)}"
                values = ", ".join(c_double(x) for x in entry["start"])
                lines.append(f"static const double {start}[] = {{{values}}};")
            fields.append(f"  {{{c_string(cap)}, {c_string(field)}, {entry['vr']}u, "
                          f"{entry['count']}u, {start}}},")

    def table(ctype: str, var: str, rows: list[str]) -> str:
        if not rows:
            return "NULL"
        lines.append(f"static const {ctype} {var}[] = {{")
        lines.extend(rows)
        lines.append("};")
        return var

    caps = table("char *const", "capabilities",
                 [f"  {c_string(c)}," for c in descriptor["capabilities"]])
    fields_var = table("cpv_model_field_t", "fields", fields)
    required = descriptor.get("required_capabilities") or []
    required_var = table("char *const", "required", [f"  {c_string(c)}," for c in required])
    params = descriptor.get("parameters") or {}
    params_var = table("cpv_model_parameter_t", "parameters",
                       [f"  {{{c_string(p)}, {e['vr']}u}}," for p, e in params.items()])
    overrides = descriptor.get("overrides") or {}
    overrides_var = table("cpv_model_override_t", "overrides",
                          [f"  {{{c_string(p)}, {c_double(x)}}}," for p, x in overrides.items()])
    marker = descriptor.get("marker")
    lines += [
        "",
        f"const cpv_model_t cpv_model_{name} = {{",
        f"  .descriptor_schema = {descriptor['descriptor_schema']},",
        f"  .contract_name = {c_string(descriptor['contract']['name'])},",
        f"  .contract_version = {descriptor['contract']['version']},",
        f"  .name = {c_string(name)},",
        f"  .profile = {c_string(descriptor['profile'])},",
        f"  .model_name = {c_string(art['model_name'])},",
        f"  .instantiation_token = {c_string(art['instantiation_token'])},",
        f"  .resources_uri = {c_string(resources_uri)},",
        f"  .source_sha256 = {c_string(art['source_sha256'])},",
        f"  .has_marker = {1 if marker else 0},",
        f"  .marker_vr = {marker['vr'] if marker else 0}u,",
        f"  .marker_value = {marker['value'] if marker else 0},",
        f"  .capabilities = {caps},",
        f"  .capability_count = {len(descriptor['capabilities'])},",
        f"  .required_capabilities = {required_var},",
        f"  .required_count = {len(required)},",
        f"  .fields = {fields_var},",
        f"  .field_count = {len(fields)},",
        f"  .parameters = {params_var},",
        f"  .parameter_count = {len(params)},",
        f"  .overrides = {overrides_var},",
        f"  .override_count = {len(overrides)},",
        "  .fmi3 = {",
        *[f"    .{member} = (cpv_fmi3_fn){function}," for member, function in FMI3_FUNCTIONS],
        "  },",
        "};",
        "",
    ]
    return "\n".join(lines)


def write_shim(descriptor: dict, extracted: Path, out_dir: Path, name: str) -> Path:
    """Write out_dir/shim/ for a prepared descriptor; returns the shim directory."""
    if not NAME_PATTERN.fullmatch(name):
        raise ValueError(f"shim name {name!r} must match {NAME_PATTERN.pattern} "
                         "(it becomes the C symbol cpv_model_NAME)")
    art = descriptor["artifact"]
    sources = extracted / "sources"
    if not sources.is_dir():
        raise ValueError(f"{art['model_name']}: the FMU has no sources/ directory, so it cannot "
                         "be linked into a host; export it with its C sources")
    files, definitions = read_build_description(sources, art["model_identifier"])
    resources_uri = None
    if art.get("resources"):
        resources_uri = f"file://{(out_dir / art['resources']).resolve()}/"
    shim = out_dir / SHIM_DIR
    if shim.exists():
        shutil.rmtree(shim)
    shutil.copytree(sources, shim / "sources")
    (shim / f"cpv_model_{name}.c").write_text(render(descriptor, name, resources_uri))
    cmake = [
        f"# Generated by cp_vehicle_interface prepare --shim {name}.",
        f"set(CPV_MODEL_NAME {name})",
        "set(CPV_MODEL_SOURCES " + " ".join(f"sources/{f}" for f in files) + ")",
        "set(CPV_MODEL_DEFINITIONS " + " ".join(definitions) + ")",
        "",
    ]
    (shim / "cpv_model.cmake").write_text("\n".join(cmake))
    return shim
