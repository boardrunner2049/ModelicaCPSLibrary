#!/usr/bin/env bash
# Fly one airframe at each IMU fidelity in ArduPilot SITL and compare.
#
#   runtime/hosts/ardupilot/imu_fidelity.sh [quad|rover|plane] [LEVEL...]
#
# LEVEL: 0 ideal, 1 digital, 2 errors, 3 electromechanical (default: 0 1 2 3).
# The airframe is configs/KIND.toml; level N adds the IMU of configs/quad_iN.toml
# (the same parameters for every airframe), so only the IMU differs. The run
# files go to build/imu-fidelity/. Every level flies the vehicle kind's mission
# check headless, all levels at once (SITL instances 1..4), each at
# min(--speedup, the model's real-time rate). I3 runs at ~0.04-0.1x real time,
# so its flight takes 15-45 minutes.
#   SPEEDUP=N  (default 2)
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
root=$(cd "$here/../../.." && pwd)
kind=${1:-rover}
shift || true
levels=("$@")
((${#levels[@]})) || levels=(0 1 2 3)
out=$root/build/imu-fidelity
mkdir -p "$out"

files=()
for n in "${levels[@]}"; do
  f=$out/imu_${kind}_i$n.toml
  python3 - "$root/configs" "$kind" "$n" "$f" <<'EOF'
import pathlib, re, sys
configs, kind, n, out = pathlib.Path(sys.argv[1]), sys.argv[2], int(sys.argv[3]), sys.argv[4]
if not (configs / f"{kind}.toml").is_file() or n not in (0, 1, 2, 3):
    sys.exit(f"imu_fidelity: no airframe {kind!r} or level {n}")
body = (configs / f"{kind}.toml").read_text()
if n:
    body += "\n[models.imu]" + (configs / f"quad_i{n}.toml").read_text().split("[models.imu]", 1)[1]
body = re.sub(r'model_name = "[^"]*"', f'model_name = "Fidelity{kind.capitalize()}I{n}"', body, count=1)
pathlib.Path(out).write_text(f"# {kind} with IMU level I{n}; generated by imu_fidelity.sh\n" + body)
EOF
  files+=("$f")
done

echo "== building ${files[*]##*/}"
"$here/build.sh" "${files[@]}" | grep -E '^==|conforms' || { echo "build failed" >&2; exit 1; }

speedup=${SPEEDUP:-2}
pids=()
for i in "${!files[@]}"; do
  f=${files[$i]}
  name=$(basename "$f" .toml)
  rate=$("$root/build/runtime-release/cpv_realtime" "$name" | awk '{print $2}')
  s=$(awk -v r="$rate" -v s="$speedup" 'BEGIN { print (r < s) ? 1 : s }')
  echo "$name: ${rate}x real time, flying at --speedup $s"
  "$here/run.sh" "$f" --headless --no-build --speedup "$s" --instance $((i + 1)) \
    > "$out/$name.log" 2>&1 &
  pids+=($!)
done
trap 'kill "${pids[@]}" 2>/dev/null' EXIT

status=0
for i in "${!files[@]}"; do
  name=$(basename "${files[$i]}" .toml)
  wait "${pids[$i]}" && result=PASSED || { result=FAILED; status=1; }
  echo "== $name: $result"
  grep -E 'hover:|landed|worst|stopped|touchdown|FAILED' "$out/$name.log" | sed 's/^/   /'
done
trap - EXIT
exit $status
